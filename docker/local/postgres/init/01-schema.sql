-- ------------------------------------------------------------------ accounts
CREATE TABLE accounts_bankaccount (
    id                uuid          PRIMARY KEY,
    created_at        timestamptz   NOT NULL,
    updated_at        timestamptz   NOT NULL,
    account_number    varchar(20)   NOT NULL UNIQUE,
    account_balance   numeric(10,2) NOT NULL,
    currency          varchar(20)   NOT NULL,
    account_status    varchar(10)   NOT NULL,
    account_type      varchar(20)   NOT NULL,
    is_primary        boolean       NOT NULL,
    kyc_submitted     boolean       NOT NULL,
    kyc_verified      boolean       NOT NULL,
    verification_date timestamptz,
    verification_notes text         NOT NULL,
    fully_activated   boolean       NOT NULL,
    user_id           uuid          NOT NULL REFERENCES user_auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    verified_by_id    uuid REFERENCES user_auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    interest_rate     numeric(5,4)  NOT NULL,
    CONSTRAINT accounts_bankaccount_user_id_currency_account_type_uniq UNIQUE (user_id, currency, account_type)
);
CREATE INDEX accounts_bankaccount_account_number_like ON accounts_bankaccount (account_number varchar_pattern_ops);
CREATE INDEX accounts_bankaccount_user_id ON accounts_bankaccount (user_id);
CREATE INDEX accounts_bankaccount_verified_by_id ON accounts_bankaccount (verified_by_id);

CREATE TABLE accounts_transaction (
    id                  uuid          PRIMARY KEY,
    created_at          timestamptz   NOT NULL,
    updated_at          timestamptz   NOT NULL,
    amount              numeric(12,2) NOT NULL,
    description         varchar(500),
    status              varchar(20)   NOT NULL,
    transaction_type    varchar(20)   NOT NULL,
    receiver_id         uuid REFERENCES user_auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    receiver_account_id uuid REFERENCES accounts_bankaccount (id) DEFERRABLE INITIALLY DEFERRED,
    sender_id           uuid REFERENCES user_auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    sender_account_id   uuid REFERENCES accounts_bankaccount (id) DEFERRABLE INITIALLY DEFERRED,
    user_id             uuid REFERENCES user_auth_user (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX accounts_tr_created_b2c597_idx ON accounts_transaction (created_at);
CREATE INDEX accounts_transaction_receiver_id ON accounts_transaction (receiver_id);
CREATE INDEX accounts_transaction_receiver_account_id ON accounts_transaction (receiver_account_id);
CREATE INDEX accounts_transaction_sender_id ON accounts_transaction (sender_id);
CREATE INDEX accounts_transaction_sender_account_id ON accounts_transaction (sender_account_id);
CREATE INDEX accounts_transaction_user_id ON accounts_transaction (user_id);

