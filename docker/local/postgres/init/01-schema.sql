-- =============================================================================
-- NextGen Bank - schema
--
-- Executed automatically by the official postgres image the first time the `postgres_data` volume is created
-- (everything in /docker-entrypoint-initdb.d runs in alphabetical order, against $POSTGRES_DB).
-- To re-run it:  docker compose -f local.yml down -v && docker compose -f local.yml up -d --build
--
-- The DDL mirrors exactly what `manage.py migrate` generates for Django 4.2 + the project's migrations, and the
-- migration history is recorded at the bottom, so `manage.py migrate` (run by the api container) finds nothing
-- left to do for these apps. django_celery_beat is the only exception: its tables belong to the library and are
-- created by its own migrations when the api container starts.
-- =============================================================================

-- ------------------------------------------------------------------ Django core
CREATE TABLE django_migrations (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app     varchar(255) NOT NULL,
    name    varchar(255) NOT NULL,
    applied timestamptz  NOT NULL
);

CREATE TABLE django_content_type (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_label varchar(100) NOT NULL,
    model     varchar(100) NOT NULL,
    CONSTRAINT django_content_type_app_label_model_76bd3d3b_uniq UNIQUE (app_label, model)
);

CREATE TABLE auth_permission (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(255) NOT NULL,
    content_type_id integer      NOT NULL REFERENCES django_content_type (id) DEFERRABLE INITIALLY DEFERRED,
    codename        varchar(100) NOT NULL,
    CONSTRAINT auth_permission_content_type_id_codename_01ab375a_uniq UNIQUE (content_type_id, codename)
);
CREATE INDEX auth_permission_content_type_id_2f476e4b ON auth_permission (content_type_id);

CREATE TABLE auth_group (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL UNIQUE
);
CREATE INDEX auth_group_name_a6ea08ec_like ON auth_group (name varchar_pattern_ops);

CREATE TABLE auth_group_permissions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      integer NOT NULL REFERENCES auth_group (id) DEFERRABLE INITIALLY DEFERRED,
    permission_id integer NOT NULL REFERENCES auth_permission (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT auth_group_permissions_group_id_permission_id_0cd325b0_uniq UNIQUE (group_id, permission_id)
);
CREATE INDEX auth_group_permissions_group_id_b120cbf9 ON auth_group_permissions (group_id);
CREATE INDEX auth_group_permissions_permission_id_84c5c92e ON auth_group_permissions (permission_id);

CREATE TABLE django_session (
    session_key  varchar(40) PRIMARY KEY,
    session_data text        NOT NULL,
    expire_date  timestamptz NOT NULL
);
CREATE INDEX django_session_expire_date_a5c62663 ON django_session (expire_date);
CREATE INDEX django_session_session_key_c0390e0f_like ON django_session (session_key varchar_pattern_ops);

CREATE TABLE django_site (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain varchar(100) NOT NULL,
    name   varchar(50)  NOT NULL,
    CONSTRAINT django_site_domain_a2e37b91_uniq UNIQUE (domain)
);

-- ------------------------------------------------------------------ user_auth
CREATE TABLE user_auth_user (
    password             varchar(128) NOT NULL,
    last_login           timestamptz,
    is_superuser         boolean      NOT NULL,
    is_staff             boolean      NOT NULL,
    is_active            boolean      NOT NULL,
    date_joined          timestamptz  NOT NULL,
    id                   uuid         PRIMARY KEY,
    username             varchar(12)  NOT NULL UNIQUE,
    security_question    varchar(30)  NOT NULL,
    security_answer      varchar(30)  NOT NULL,
    email                varchar(254) NOT NULL UNIQUE,
    first_name           varchar(30)  NOT NULL,
    middle_name          varchar(30),
    last_name            varchar(30)  NOT NULL,
    id_no                integer      NOT NULL UNIQUE CHECK (id_no >= 0),
    account_status       varchar(10)  NOT NULL,
    role                 varchar(20)  NOT NULL,
    failed_login_attempts smallint    NOT NULL CHECK (failed_login_attempts >= 0),
    last_failed_login    timestamptz,
    otp                  varchar(6)   NOT NULL,
    otp_expiry_time      timestamptz
);
CREATE INDEX user_auth_user_username_like ON user_auth_user (username varchar_pattern_ops);
CREATE INDEX user_auth_user_email_like ON user_auth_user (email varchar_pattern_ops);

CREATE TABLE user_auth_user_groups (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  uuid    NOT NULL REFERENCES user_auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    group_id integer NOT NULL REFERENCES auth_group (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT user_auth_user_groups_user_id_group_id_uniq UNIQUE (user_id, group_id)
);
CREATE INDEX user_auth_user_groups_user_id ON user_auth_user_groups (user_id);
CREATE INDEX user_auth_user_groups_group_id ON user_auth_user_groups (group_id);

CREATE TABLE user_auth_user_user_permissions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       uuid    NOT NULL REFERENCES user_auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    permission_id integer NOT NULL REFERENCES auth_permission (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT user_auth_user_user_permissions_user_id_permission_id_uniq UNIQUE (user_id, permission_id)
);
CREATE INDEX user_auth_user_user_permissions_user_id ON user_auth_user_user_permissions (user_id);
CREATE INDEX user_auth_user_user_permissions_permission_id ON user_auth_user_user_permissions (permission_id);

CREATE TABLE django_admin_log (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_time     timestamptz  NOT NULL,
    object_id       text,
    object_repr     varchar(200) NOT NULL,
    action_flag     smallint     NOT NULL CHECK (action_flag >= 0),
    change_message  text         NOT NULL,
    content_type_id integer REFERENCES django_content_type (id) DEFERRABLE INITIALLY DEFERRED,
    user_id         uuid    NOT NULL REFERENCES user_auth_user (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX django_admin_log_content_type_id_c4bce8eb ON django_admin_log (content_type_id);
CREATE INDEX django_admin_log_user_id_c564eba6 ON django_admin_log (user_id);

